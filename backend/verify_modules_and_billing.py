import os
import django
import uuid
from datetime import date, timedelta

os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'config.settings')
django.setup()

from rest_framework.test import APIClient
from apps.accounts.models import User, UserRole
from apps.students.models import Student, StudentStatus, Parent
from apps.academics.models import AcademicYear, Term, Class, Stream, Subject, TeacherAssignment, AcademicCalendar, CalendarEventType
from apps.fees.models import FeeStructure, FeeItem, Invoice, Payment, PaymentMethod
from apps.attendance.models import Attendance, AttendanceStatus, AttendanceType
from apps.staff.models import Teacher

def run_tests():
    print("=== STARTING COMPREHENSIVE VERIFICATION: STUDENT MANAGEMENT, ACADEMICS, ATTENDANCE & BILLING ===")
    client = APIClient()
    admin_user = User.objects.filter(role=UserRole.ADMIN).first()
    if not admin_user:
        admin_user = User.objects.create_superuser('admin_test@school.edu', 'admin_test', 'Password123!', role=UserRole.ADMIN)
    client.force_authenticate(user=admin_user)

    # 1. SETUP ACADEMIC HIERARCHY
    print("\n--- 1. Testing Academic Hierarchy: Academic Year -> Term -> Class -> Stream ---")
    today = date.today()
    acad_year, _ = AcademicYear.objects.get_or_create(
        name="2026/2027 Academic Year",
        defaults={"start_date": today, "end_date": today + timedelta(days=365), "is_current": True}
    )
    term, _ = Term.objects.get_or_create(
        academic_year=acad_year,
        name="Term 1 2026",
        defaults={"start_date": today, "end_date": today + timedelta(days=90), "is_current": True}
    )
    test_class, _ = Class.objects.get_or_create(
        code="FORM-1",
        defaults={
            "name": "Form 1",
            "academic_stage": "SECONDARY",
            "academic_year": acad_year,
            "term": term,
            "order": 1
        }
    )
    test_stream, _ = Stream.objects.get_or_create(
        class_obj=test_class,
        name="Stream Alpha",
        defaults={"capacity": 45}
    )
    print(f"Academic Hierarchy OK: {acad_year.name} -> {term.name} -> {test_class.name} -> {test_stream.name}")

    # Setup Fee Structure for this class so registration auto-billing triggers!
    fee_struct, _ = FeeStructure.objects.get_or_create(
        academic_year=acad_year,
        term=term,
        class_obj=test_class,
        defaults={"total_amount": 450000.00, "due_date": today + timedelta(days=30)}
    )
    FeeItem.objects.get_or_create(
        fee_structure=fee_struct,
        name="Tuition Fee",
        defaults={"amount": 450000.00, "is_mandatory": True}
    )
    print(f"Fee Structure configured for {test_class.name}: {fee_struct.total_amount} TZS")

    # 2. TEST STUDENT REGISTRATION & AUTO-BILLING
    print("\n--- 2. Testing Student Registration & Automatic Invoice Generation ---")
    adm_no = f"ADM-{uuid.uuid4().hex[:6].upper()}"
    student_payload = {
        "admission_number": adm_no,
        "first_name": "Neema",
        "last_name": "Juma",
        "email": f"neema_{uuid.uuid4().hex[:4]}@school.edu",
        "gender": "FEMALE",
        "date_of_birth": "2010-05-15",
        "admission_date": str(today),
        "current_class": str(test_class.id),
        "current_stream": str(test_stream.id),
        "academic_year": str(acad_year.id),
        "address": "123 Uhuru Road, Dar es Salaam",
        "phone_number": "+255712345678",
        "status": "ACTIVE",
        "profile_photo": "https://images.unsplash.com/photo-1544717305-2782549b5136?w=150",
        "parent_first_name": "Juma",
        "parent_last_name": "Omari",
        "parent_email": f"juma_{uuid.uuid4().hex[:4]}@parent.edu",
        "parent_phone": "+255789012345"
    }

    reg_resp = client.post('/api/v1/students/', data=student_payload, format='json')
    assert reg_resp.status_code in [200, 201], f"Registration failed: {reg_resp.data}"
    student_data = reg_resp.data
    student_id = student_data['id']
    print(f"Student Registered Successfully! ID: {student_id}, Admission: {student_data['admission_number']}")
    print(f"Student Profile Attributes: Status={student_data.get('status')}, Address={student_data.get('address')}, Phone={student_data.get('phone_number')}, Photo={bool(student_data.get('profile_photo'))}")

    # Check if Invoice was automatically generated by post_save signal
    invoices = Invoice.objects.filter(student_id=student_id)
    assert invoices.exists(), "Auto-billing signal failed: No invoice created for registered student!"
    auto_inv = invoices.first()
    print(f"Auto-Billing Verified: Generated Invoice {auto_inv.invoice_number} with amount {auto_inv.total_amount} TZS and balance {auto_inv.balance} TZS")

    # 3. TEST PAYMENT TO CLEAR INVOICE
    print("\n--- 3. Testing Fee Payment and Invoice Balance Recalculation ---")
    pay_payload = {
        "invoice": str(auto_inv.id),
        "amount": 200000.00,
        "payment_method": "BANK_TRANSFER",
        "payment_date": str(today),
        "reference_number": f"BANK-REF-{uuid.uuid4().hex[:6].upper()}",
        "notes": "First installment payment"
    }
    pay_resp = client.post('/api/v1/payments/', data=pay_payload, format='json')
    assert pay_resp.status_code in [200, 201], f"Payment recording failed: {pay_resp.data}"
    auto_inv.refresh_from_db()
    print(f"Payment Recorded: {pay_resp.data.get('payment_number')}. New Invoice Balance: {auto_inv.balance} TZS, Status: {auto_inv.status}")
    assert auto_inv.balance == 250000.00, f"Expected 250000.00 balance, got {auto_inv.balance}"

    # 4. TEST STUDENT STATUS TRANSITION & STATS
    print("\n--- 4. Testing Student Status Transitions & Statistics ---")
    status_resp = client.post(f'/api/v1/students/{student_id}/change_status/', data={"status": "SUSPENDED"}, format='json')
    assert status_resp.status_code == 200, f"Status change failed: {status_resp.data}"
    assert status_resp.data['student']['status'] == "SUSPENDED"
    print(f"Status transition to SUSPENDED successful: {status_resp.data['message']}")

    # Switch back to ACTIVE
    client.post(f'/api/v1/students/{student_id}/change_status/', data={"status": "ACTIVE"}, format='json')

    stats_resp = client.get('/api/v1/students/statistics/')
    assert stats_resp.status_code == 200, f"Stats failed: {stats_resp.data}"
    print(f"Student Statistics: Total={stats_resp.data['total_students']}, Active={stats_resp.data['active']}, Gender={stats_resp.data['gender_breakdown']}")

    # 5. TEST TEACHER ASSIGNMENTS & CALENDAR
    print("\n--- 5. Testing Academic Teacher Assignment & Academic Calendar ---")
    test_subject, _ = Subject.objects.get_or_create(code="BIO-101", defaults={"name": "Biology", "department": "Sciences"})
    teacher = Teacher.objects.first()
    if not teacher:
        t_user = User.objects.create_user(
            email=f"teacher_{uuid.uuid4().hex[:4]}@school.edu",
            username=f"teacher_{uuid.uuid4().hex[:4]}",
            password="Password123!",
            first_name="Samson",
            last_name="Mwalimu",
            role=UserRole.TEACHER
        )
        teacher = Teacher.objects.create(user=t_user, employee_id=f"TCH-{uuid.uuid4().hex[:4].upper()}", designation="Senior Teacher")

    assign_payload = {
        "teacher": str(teacher.id),
        "subject": str(test_subject.id),
        "class_obj": str(test_class.id),
        "stream": str(test_stream.id),
        "academic_year": str(acad_year.id),
        "term": str(term.id),
        "is_class_teacher": True,
        "periods_per_week": 5
    }
    TeacherAssignment.objects.filter(
        teacher=teacher, subject=test_subject, class_obj=test_class,
        stream=test_stream, academic_year=acad_year, term=term
    ).delete()
    assign_resp = client.post('/api/v1/academics/assignments/', data=assign_payload, format='json')
    assert assign_resp.status_code in [200, 201], f"Teacher assignment failed: {assign_resp.data}"
    print(f"Teacher Assignment Created: {assign_resp.data.get('teacher_name')} -> {assign_resp.data.get('subject_name')} ({assign_resp.data.get('class_name')})")

    # Create Calendar Event via API
    cal_payload = {
        "academic_year": str(acad_year.id),
        "term": str(term.id),
        "title": "Mid-term Examinations",
        "description": "Mid-term assessment for all secondary forms",
        "event_type": "EXAMINATION",
        "start_date": str(today + timedelta(days=30)),
        "end_date": str(today + timedelta(days=35)),
        "is_public": True
    }
    cal_resp = client.post('/api/v1/academics/calendar/', data=cal_payload, format='json')
    assert cal_resp.status_code in [200, 201], f"Calendar event failed: {cal_resp.data}"
    print(f"Calendar Event Created: {cal_resp.data.get('title')} ({cal_resp.data.get('event_type')}) from {cal_resp.data.get('start_date')} to {cal_resp.data.get('end_date')}")

    # 6. TEST ATTENDANCE MODULE
    print("\n--- 6. Testing Attendance Recording (Daily, Class, Subject) ---")
    st_instance = Student.objects.get(id=student_id)
    # Bulk mark attendance
    bulk_att_payload = {
        "date": str(today),
        "stream_id": str(test_stream.id),
        "attendance_type": "DAILY",
        "records": [
            {"student_id": str(student_id), "status": "PRESENT", "notes": "Prompt arrival"}
        ]
    }
    bulk_resp = client.post('/api/v1/attendance/records/bulk_mark/', data=bulk_att_payload, format='json')
    assert bulk_resp.status_code == 200, f"Bulk mark failed: {bulk_resp.data}"
    print(f"Bulk Attendance Recorded: {bulk_resp.data.get('message')}")

    # Record Subject Attendance
    subj_att = Attendance.objects.create(
        student=st_instance,
        stream=test_stream,
        subject=test_subject,
        date=today,
        attendance_type=AttendanceType.SUBJECT,
        status=AttendanceStatus.LATE,
        notes="Late by 10 mins",
        recorded_by=admin_user
    )
    print(f"Subject Attendance Recorded: {subj_att.subject.name} - {subj_att.status}")

    # Test Reports Endpoint
    rep_resp = client.get('/api/v1/attendance/records/reports/')
    assert rep_resp.status_code == 200, f"Attendance reports failed: {rep_resp.data}"
    rep_data = rep_resp.data
    print(f"Attendance Report: Overall Rate = {rep_data['overall_summary']['overall_attendance_rate']}%, Total = {rep_data['overall_summary']['total_records']}")

    # 7. TEST STUDENT & PARENT RESTRICTED ACCESS
    print("\n--- 7. Testing Student and Parent Self-Service Scoping ---")
    # Student view
    student_user = st_instance.user
    client.force_authenticate(user=student_user)
    st_att_resp = client.get('/api/v1/attendance/me/')
    assert st_att_resp.status_code == 200, f"Student self-service attendance failed: {st_att_resp.data}"
    print(f"Student Self-Service Attendance OK: Student={st_att_resp.data['student_name']}, Rate={st_att_resp.data['summary']['attendance_rate']}%")

    # Parent view
    parent_user = st_instance.parent.user
    client.force_authenticate(user=parent_user)
    par_att_resp = client.get(f'/api/v1/attendance/me/?student_id={student_id}')
    assert par_att_resp.status_code == 200, f"Parent viewing child attendance failed: {par_att_resp.data}"
    print(f"Parent Linked Ward Attendance OK: Child={par_att_resp.data['student_name']}, Rate={par_att_resp.data['summary']['attendance_rate']}%")

    print("\n>>> ALL TEST CASES PASSED WITH 100% SUCCESS! <<<")

if __name__ == '__main__':
    run_tests()
